-- WhatsApp Business (Cloud API) connection of each workspace.

-- Resolves the public key in the webhook URL to its workspace before the workspace is known, like widget keys. No
-- row-level security on purpose, and nothing secret in it
CREATE TABLE whatsapp_channel_keys (
    channel_key  TEXT PRIMARY KEY,
    workspace_id UUID NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
    CONSTRAINT whatsapp_channel_keys_workspace_key UNIQUE (workspace_id)
);

CREATE TABLE whatsapp_channels (
    workspace_id         UUID        PRIMARY KEY REFERENCES workspaces (id) ON DELETE CASCADE,
    phone_number_id      TEXT        NOT NULL,
    display_phone_number TEXT,
    -- Encrypted at rest: the token sends messages as the business, the app secret verifies Meta's signatures
    access_token         TEXT        NOT NULL,
    app_secret           TEXT        NOT NULL,
    -- Generated by the platform and pasted into Meta's webhook settings
    verify_token         TEXT        NOT NULL,
    enabled              BOOLEAN     NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL,
    updated_at           TIMESTAMPTZ NOT NULL
);

-- Meta delivers a webhook again when it gets no quick answer; a message id seen before is ignored
CREATE TABLE whatsapp_inbound_messages (
    workspace_id UUID        NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
    message_id   TEXT        NOT NULL,
    received_at  TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (workspace_id, message_id)
);

ALTER TABLE whatsapp_channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE whatsapp_channels FORCE ROW LEVEL SECURITY;
CREATE POLICY workspace_isolation ON whatsapp_channels
    USING (workspace_id = current_workspace_id())
    WITH CHECK (workspace_id = current_workspace_id());

ALTER TABLE whatsapp_inbound_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE whatsapp_inbound_messages FORCE ROW LEVEL SECURITY;
CREATE POLICY workspace_isolation ON whatsapp_inbound_messages
    USING (workspace_id = current_workspace_id())
    WITH CHECK (workspace_id = current_workspace_id());
